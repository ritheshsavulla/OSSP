/**
 * Master Simulation Engine for Virtual Memory, TLB, Page Table, and RAM
 * Coordinates execution flow, step-by-step state tracking, EAT calculations,
 * and event pub/sub for the UI.
 */

import { AddressDecoder } from './address.js';
import { TLB } from './tlb.js';
import { PageTableManager } from './pageTable.js';
import { PhysicalMemoryManager } from './memory.js';
import { WorkloadGenerator } from './workloads.js';

export class MemorySimulator {
  constructor(initialConfig = {}) {
    this.config = {
      addressBits: 16,
      pageSize: 1024, // 1 KB
      ramSize: 16384, // 16 KB (16 frames)
      tlbSize: 8,
      tlbAssociativity: 'fully', // 'fully', '2-way', '4-way'
      tlbPolicy: 'LRU',
      pagingType: 'single', // 'single', 'two-level', 'inverted'
      outerBits: 3,
      memPolicy: 'LRU', // Page replacement policy: LRU, FIFO, Clock, Optimal, Random
      tlbLatency: 1, // ns
      ramLatency: 100, // ns
      pageFaultLatency: 8000000, // 8 ms = 8,000,000 ns
      swapLatency: 10000000, // 10 ms
      ...initialConfig,
    };

    this.subscribers = new Set();
    this.history = [];
    this.trace = [];
    this.traceIndex = 0;
    this.isRunning = false;
    this.playSpeed = 1; // 1x
    this.timer = null;

    this.initEngines();
  }

  initEngines() {
    this.decoder = new AddressDecoder({
      addressBits: this.config.addressBits,
      pageSize: this.config.pageSize,
      pagingType: this.config.pagingType,
      outerBits: this.config.outerBits,
    });

    this.tlb = new TLB({
      size: this.config.tlbSize,
      associativity: this.config.tlbAssociativity,
      policy: this.config.tlbPolicy,
      accessLatency: this.config.tlbLatency,
    });

    const numFrames = Math.max(2, Math.floor(this.config.ramSize / this.config.pageSize));

    this.pageTable = new PageTableManager({
      pagingType: this.config.pagingType,
      numVirtualPages: this.decoder.numVirtualPages,
      numFrames,
      outerBits: this.decoder.outerBits,
      innerBits: this.decoder.innerBits,
      accessLatency: this.config.ramLatency,
    });

    this.memory = new PhysicalMemoryManager({
      ramSize: this.config.ramSize,
      pageSize: this.config.pageSize,
      policy: this.config.memPolicy,
      pageFaultLatency: this.config.pageFaultLatency,
      swapLatency: this.config.swapLatency,
    });

    this.workloads = new WorkloadGenerator(this.config.pageSize, this.decoder.maxAddress);

    this.stats = {
      totalAccesses: 0,
      reads: 0,
      writes: 0,
      tlbHits: 0,
      tlbMisses: 0,
      pageHits: 0,
      pageFaults: 0,
      dirtyEvictions: 0,
      totalLatencyNs: 0,
    };

    this.currentStepResult = null;
  }

  updateConfiguration(newConfig) {
    this.stopAutoRun();
    this.config = { ...this.config, ...newConfig };
    this.initEngines();
    this.history = [];
    this.traceIndex = 0;
    this.notify('configChange', this.config);
  }

  reset() {
    this.stopAutoRun();
    this.tlb.reset();
    this.pageTable.reset();
    this.memory.reset();
    this.history = [];
    this.traceIndex = 0;
    this.stats = {
      totalAccesses: 0,
      reads: 0,
      writes: 0,
      tlbHits: 0,
      tlbMisses: 0,
      pageHits: 0,
      pageFaults: 0,
      dirtyEvictions: 0,
      totalLatencyNs: 0,
    };
    this.currentStepResult = null;
    this.notify('reset');
  }

  subscribe(callback) {
    this.subscribers.add(callback);
    return () => this.subscribers.delete(callback);
  }

  notify(event, data) {
    for (const sub of this.subscribers) {
      try {
        sub(event, data, this);
      } catch (err) {
        console.error('Subscriber error:', err);
      }
    }
  }

  /**
   * Execute translation for a single logical address
   */
  translate(inputAddress, operation = 'R', pid = 1, futureTrace = []) {
    const isWrite = operation.toUpperCase() === 'W';
    this.stats.totalAccesses++;
    if (isWrite) this.stats.writes++;
    else this.stats.reads++;

    // 1. Decode address
    const dec = this.decoder.decompose(inputAddress);
    const vpn = dec.vpn;
    const offset = dec.offset;

    const timeline = [];
    timeline.push({
      step: 1,
      title: 'Address Generated by CPU',
      detail: `Logical Address: ${dec.hex} (${operation}) | VPN: ${dec.vpnHex} | Offset: ${dec.offsetHex}`,
      type: 'cpu',
    });

    let frame = null;
    let tlbHit = false;
    let tlbEvicted = null;
    let pageFault = false;
    let memEvicted = null;
    let dirtyWriteback = false;
    let totalLatency = 0;

    // 2. TLB parallel search
    totalLatency += this.config.tlbLatency;
    const tlbLookup = this.tlb.lookup(vpn, pid, isWrite);

    if (tlbLookup.hit) {
      // ===== TLB HIT =====
      tlbHit = true;
      frame = tlbLookup.frame;
      this.stats.tlbHits++;

      // Access physical frame directly
      this.memory.accessFrame(frame, isWrite);
      totalLatency += this.config.ramLatency;

      timeline.push({
        step: 2,
        title: 'TLB Hit (Fast Path)',
        detail: `Tag matched in TLB slot #${tlbLookup.index}. Retrieved Frame #${frame}.`,
        type: 'tlb-hit',
      });
    } else {
      // ===== TLB MISS =====
      this.stats.tlbMisses++;
      timeline.push({
        step: 2,
        title: 'TLB Miss',
        detail: `VPN ${dec.vpnHex} not present in TLB. Fallback to Page Table lookup.`,
        type: 'tlb-miss',
      });

      // 3. Page Table Lookup
      const ptLookup = this.pageTable.lookup(dec, pid);
      totalLatency += ptLookup.latency;

      if (!ptLookup.pageFault) {
        // ===== PAGE TABLE HIT =====
        frame = ptLookup.frame;
        this.stats.pageHits++;

        timeline.push({
          step: 3,
          title: 'Page Table Hit',
          detail: `Page Table resolved VPN ${dec.vpnHex} -> Frame #${frame} (Present=1).`,
          type: 'pt-hit',
        });

        // Insert into TLB
        const insertResult = this.tlb.insert(vpn, frame, pid, isWrite);
        if (insertResult.replaced) {
          tlbEvicted = insertResult.evicted;
          timeline.push({
            step: 4,
            title: `TLB Update & Eviction (${this.config.tlbPolicy})`,
            detail: `TLB full: Evicted VPN 0x${tlbEvicted.tag.toString(16).toUpperCase()} to cache new mapping.`,
            type: 'tlb-evict',
          });
        }

        // Access RAM
        this.memory.accessFrame(frame, isWrite);
        totalLatency += this.config.ramLatency;
      } else {
        // ===== PAGE FAULT =====
        pageFault = true;
        this.stats.pageFaults++;

        timeline.push({
          step: 3,
          title: 'PAGE FAULT Detected (Present=0)',
          detail: `Page ${dec.vpnHex} is not resident in Physical RAM! Trap to OS Kernel.`,
          type: 'page-fault',
        });

        // 4. Physical Frame Allocation & Replacement
        const allocResult = this.memory.allocateFrame(vpn, pid, futureTrace);
        frame = allocResult.frameId;
        dirtyWriteback = allocResult.dirtyWriteback;
        totalLatency += allocResult.serviceLatency;

        if (allocResult.evicted) {
          memEvicted = allocResult.evicted;
          const evictedVpn = memEvicted.vpn;

          // Writeback to swap disk if dirty
          if (dirtyWriteback) {
            this.stats.dirtyEvictions++;
            timeline.push({
              step: 4,
              title: 'Victim Dirty Page Writeback',
              detail: `Victim Frame #${frame} (VPN 0x${evictedVpn.toString(16).toUpperCase()}) was dirty. Written to Swap Disk.`,
              type: 'swap-write',
            });
          }

          // Unmap victim in Page Table
          this.pageTable.unmapPage(evictedVpn, memEvicted.frameId);

          // TLB Shootdown: Invalidate evicted page in TLB if cached
          this.tlb.invalidate(evictedVpn, pid);

          timeline.push({
            step: 5,
            title: `RAM Eviction (${this.config.memPolicy}) & TLB Shootdown`,
            detail: `Evicted VPN 0x${evictedVpn.toString(16).toUpperCase()} from Frame #${frame}. Invalidated in TLB.`,
            type: 'mem-evict',
          });
        }

        // Map page in Page Table
        this.pageTable.mapPage(vpn, frame, pid, isWrite);

        timeline.push({
          step: 6,
          title: 'Page In Loaded from Swap to RAM',
          detail: `Demanded page loaded into Frame #${frame}. Page Table entry updated (Present=1).`,
          type: 'page-in',
        });

        // Insert into TLB
        const insertResult = this.tlb.insert(vpn, frame, pid, isWrite);
        if (insertResult.replaced) {
          tlbEvicted = insertResult.evicted;
        }

        // Mark access
        this.memory.accessFrame(frame, isWrite);
        totalLatency += this.config.ramLatency;
      }
    }

    // 5. Assemble Physical Address
    const physAddr = this.decoder.assemblePhysicalAddress(frame, offset);
    timeline.push({
      step: timeline.length + 1,
      title: 'Physical Address Assembled & Memory Accessed',
      detail: `Physical Address: ${physAddr.hex} (Frame #${frame} | Offset: ${dec.offsetHex}) | Total Latency: ${this.formatLatency(totalLatency)}`,
      type: 'complete',
    });

    this.stats.totalLatencyNs += totalLatency;

    const result = {
      timestamp: Date.now(),
      stepNumber: this.history.length + 1,
      logicalAddress: dec,
      physicalAddress: physAddr,
      operation,
      pid,
      frame,
      tlbHit,
      tlbEvicted,
      pageFault,
      memEvicted,
      dirtyWriteback,
      totalLatency,
      timeline,
      eat: this.calculateEAT(),
    };

    this.currentStepResult = result;
    this.history.push(result);

    this.notify('step', result);
    return result;
  }

  formatLatency(ns) {
    if (ns >= 1000000) {
      return (ns / 1000000).toFixed(2) + ' ms';
    } else if (ns >= 1000) {
      return (ns / 1000).toFixed(2) + ' µs';
    }
    return ns + ' ns';
  }

  /**
   * Calculate Theoretical and Empirical Effective Access Time (EAT)
   */
  calculateEAT() {
    const total = this.stats.totalAccesses;
    const empirical = total > 0 ? this.stats.totalLatencyNs / total : this.config.ramLatency;

    const hitRate = total > 0 ? this.stats.tlbHits / total : 0.8;
    const missRate = 1 - hitRate;
    const pageFaultRate = total > 0 ? this.stats.pageFaults / total : 0.001;

    const tlbTime = this.config.tlbLatency;
    const ramTime = this.config.ramLatency;
    const ptLevels = this.config.pagingType === 'two-level' ? 2 : 1;
    const faultTime = this.config.pageFaultLatency;

    // EAT = HitRate * (tlb + ram) + MissRate * (tlb + (1 - p)*(levels*ram + ram) + p*(faultTime))
    const hitComponent = hitRate * (tlbTime + ramTime);
    const missComponent = missRate * (
      tlbTime +
      (1 - pageFaultRate) * (ptLevels * ramTime + ramTime) +
      pageFaultRate * (faultTime + ramTime)
    );
    const theoretical = hitComponent + missComponent;

    return {
      empirical,
      empiricalFormatted: this.formatLatency(empirical),
      theoretical,
      theoreticalFormatted: this.formatLatency(theoretical),
      hitRate: (hitRate * 100).toFixed(2),
      pageFaultRate: (pageFaultRate * 100).toFixed(4),
      ptLevels,
    };
  }

  loadTrace(traceItems) {
    this.stopAutoRun();
    this.trace = traceItems;
    this.traceIndex = 0;
    this.notify('traceLoaded', { count: traceItems.length });
  }

  /**
   * Step to next instruction in the loaded trace
   */
  stepNext() {
    if (!this.trace || this.trace.length === 0) return null;
    if (this.traceIndex >= this.trace.length) {
      this.stopAutoRun();
      this.notify('traceFinished');
      return null;
    }

    const item = this.trace[this.traceIndex];
    const futureSlice = this.trace.slice(this.traceIndex + 1);
    this.traceIndex++;

    const result = this.translate(item.address, item.operation || 'R', item.pid || 1, futureSlice);
    return result;
  }

  startAutoRun(speedMultiplier = 1) {
    this.playSpeed = speedMultiplier;
    this.isRunning = true;
    this.notify('autoRunState', { running: true });

    const runStep = () => {
      if (!this.isRunning) return;
      if (this.traceIndex >= this.trace.length) {
        this.stopAutoRun();
        this.notify('traceFinished');
        return;
      }
      this.stepNext();
      const delay = Math.max(50, Math.floor(600 / this.playSpeed));
      this.timer = setTimeout(runStep, delay);
    };

    runStep();
  }

  stopAutoRun() {
    this.isRunning = false;
    if (this.timer) {
      clearTimeout(this.timer);
      this.timer = null;
    }
    this.notify('autoRunState', { running: false });
  }

  toggleAutoRun() {
    if (this.isRunning) {
      this.stopAutoRun();
    } else {
      if (this.traceIndex >= this.trace.length) {
        this.traceIndex = 0; // Loop or restart
      }
      this.startAutoRun(this.playSpeed);
    }
  }

  setSpeed(multiplier) {
    this.playSpeed = multiplier;
  }
}
